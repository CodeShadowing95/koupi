// Fichier Excel (.xlsx) minimal, sans dépendance : une feuille, en-tête en gras et figé, filtres, largeurs de colonnes.
// Un .xlsx est une archive ZIP de fichiers XML ; on l'écrit sans compression (« stored »), ce que tous les tableurs lisent.
// Les textes sont des « inline strings » : jamais interprétés comme des formules, donc pas d'injection possible.

export type XlsxValue = string | number | boolean | null | undefined;
export type XlsxSheet = { name: string; headers: string[]; rows: XlsxValue[][] };

const encoder = new TextEncoder();

// XML 1.0 refuse les caractères de contrôle (sauf tabulation et retours à la ligne).
// eslint-disable-next-line no-control-regex
const INVALID_XML = /[\u0000-\u0008\u000B\u000C\u000E-\u001F￾￿]/g;
export function xmlEscape(text: string): string {
  return text.replace(INVALID_XML, '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

/** Lettres de colonne Excel : 0 → A, 25 → Z, 26 → AA. */
export function columnName(index: number): string {
  let name = '';
  for (let n = index + 1; n > 0; n = Math.floor((n - 1) / 26)) name = String.fromCharCode(65 + ((n - 1) % 26)) + name;
  return name;
}

/** Nom de feuille accepté par Excel : 31 caractères au plus, sans : \ / ? * [ ]. */
export function sheetName(name: string): string {
  return name.replace(/[:\\/?*[\]]/g, ' ').trim().slice(0, 31) || 'Feuille1';
}

function cell(value: XlsxValue, ref: string, style: number): string {
  const s = style ? ` s="${style}"` : '';
  if (value === null || value === undefined || value === '') return '';
  if (typeof value === 'number' && Number.isFinite(value)) return `<c r="${ref}"${s}><v>${value}</v></c>`;
  const text = typeof value === 'boolean' ? (value ? 'oui' : 'non') : String(value);
  return `<c r="${ref}"${s} t="inlineStr"><is><t xml:space="preserve">${xmlEscape(text)}</t></is></c>`;
}

function worksheet({ headers, rows }: XlsxSheet): string {
  const all = [headers, ...rows];
  const lastCol = columnName(Math.max(headers.length, 1) - 1);
  const widths = headers.map((_, col) => Math.min(60, Math.max(8, ...all.map(row => String(row[col] ?? '').length + 2))));
  const sheetRows = all.map((row, r) => `<row r="${r + 1}">${row.map((value, c) => cell(value, `${columnName(c)}${r + 1}`, r === 0 ? 1 : 0)).join('')}</row>`).join('');
  return '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
    + '<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">'
    + `<dimension ref="A1:${lastCol}${all.length}"/>`
    + '<sheetViews><sheetView workbookViewId="0"><pane ySplit="1" topLeftCell="A2" activePane="bottomLeft" state="frozen"/></sheetView></sheetViews>'
    + '<sheetFormatPr defaultRowHeight="15"/>'
    + `<cols>${widths.map((width, i) => `<col min="${i + 1}" max="${i + 1}" width="${width}" customWidth="1"/>`).join('')}</cols>`
    + `<sheetData>${sheetRows}</sheetData>`
    + `<autoFilter ref="A1:${lastCol}${all.length}"/>`
    + '</worksheet>';
}

